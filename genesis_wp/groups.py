"""Register groups and categories (requirement-12, design_decision-1).

Two levels per register, both register data:

- **group**: the vendor document section the register is listed in, decided by the
  assignment rule of interface_spec-5 (Stiebel section first, then Thermia section, then
  the Thermia address-list text, then the library name). Broad sections are refined into
  the heat pump's circuits (brine, condenser, refrigerant, compressor). Stiebel section 2.12
  "Steuerung Stromaufnahme" is its own group, power_consumption_control, with the
  smart-grid state (input 82) by description. A register has the same group on every model.
- **category**: the reference code both documents print per row ("Bezug auf" /
  "Reference to"); rows without one are controller-wide. It follows from the group.

Alarms keep group ``alarms`` and also name the group whose sensor or process they concern.
"""

