def register_group(name: str) -> str:
    """The group of a register; KeyError for a register no model enables."""
    return REGISTER_GROUPS[name]


def register_category(name: str) -> str:
    """The category of a register, from its group."""
    return GROUP_CATEGORY[REGISTER_GROUPS[name]]


def register_concerns(name: str) -> str | None:
    """For an alarm, the group it concerns; None for other registers and controller-wide alarms."""
    if REGISTER_GROUPS[name] != "alarms":
        return None
    for fragment, group in ALARM_CONCERNS:
        if fragment in name:
            return group
    return None
